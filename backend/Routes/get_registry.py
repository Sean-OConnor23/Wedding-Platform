# Routes/get_registry.py
import azure.functions as func
import json
import logging
from azure.cosmos import CosmosClient
from Utils.config import get_setting, get_credential

registry_bp = func.Blueprint()

@registry_bp.route(route="get-registry", methods=["GET"])
def get_registry(req: func.HttpRequest) -> func.HttpResponse:
    logging.info("Compiling client registry list from pre-cached database values.")

    try:
        COSMOS_DB_ENDPOINT = get_setting("AZURE-COSMOSDB-ENDPOINT")
        COSMOS_DATABASE_NAME = get_setting("AZURE-COSMOSDB-DB")
        # Ensure this pulls your exact container tracking name configuration parameter
        REGISTRY_CONTAINER_NAME = get_setting("AZURE-COSMOSDB-REGISTRY-CONTAINER") 
        
        cosmos_client = CosmosClient(url=COSMOS_DB_ENDPOINT, credential=get_credential())
        container = cosmos_client.get_database_client(COSMOS_DATABASE_NAME).get_container_client(REGISTRY_CONTAINER_NAME)
        # Pull wishlist items that are still active
        query = "SELECT * FROM c WHERE c.purchasedQuantity < c.requestedQuantity"
        items = list(container.query_items(query=query, enable_cross_partition_query=True))

        optimized_registry = []

        for item in items:
            original_price = float(item.get("originalPrice", 0.0))
            best_alternative_price = float(item.get("cachedAlternativePrice", original_price))

            # Read straight from the pre-cached variables generated by the daily cron job
            optimized_registry.append({
                "id": item.get("id"),
                "title": item.get("title", "Registry Gift Item"),
                "originalPrice": original_price,
                "originalStore": item.get("originalStore"),
                "originalRegistryUrl": item.get("originalRegistryUrl"),
                "bestAlternativePrice": best_alternative_price,
                "cheaperMerchant": item.get("cachedCheaperMerchant"),
                "dealFound": bool(item.get("cachedDealFound", False)),
                "couponCode": item.get("cachedCouponCode"),
                "savingsAmount": round(original_price - best_alternative_price, 2)
              })

        return func.HttpResponse(json.dumps(optimized_registry), status_code=200, mimetype="application/json")

    except Exception as ex:
        logging.error(f"Fast registry cache retrieval failure: {str(ex)}")
        return func.HttpResponse(
            json.dumps({"error": "Failed to compile registry index view"}),
            status_code=500, mimetype="application/json"
        )
